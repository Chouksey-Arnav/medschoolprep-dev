// ─────────────────────────────────────────────────────────────────────────────
// Competitions, expansion set.
//
// The original src/data/roadmap/competitions.js carried seventeen entries, which
// was enough to prove the track worked and nowhere near enough to build a year
// out of. A roadmap that offers a tenth-grader the same four contests as every
// other tenth-grader is a template with their name on it. This file is the rest
// of the field: fifty-four more, chosen to span the actual range of what a
// pre-health student can enter.
//
// Everything here is held to the SAME rules as the original file and
// src/data/roadmap/schema.js — read that header first. The three that bite
// hardest while authoring this particular track:
//
//  1. REAL AND VERIFIABLE. Every entry is a competition that exists, run by an
//     organization that exists, at a URL that is the program's own page. No
//     invented contests, no "regional science competition" placeholders, and no
//     search-engine links (the verify script rejects those explicitly).
//
//  2. NO PAY-TO-ATTEND PRESTIGE PRODUCTS. The line src/data/opportunities.js
//     draws applies here without exception, and this is the track where the
//     temptation is greatest: the youth "leadership summits" and "national
//     academies of future physicians" that mail congratulatory nominations to
//     teenagers market themselves exactly like the entries below and are worth
//     nothing on an application. None of them are in this file, however well
//     they rank. Every entry here is free to enter, entry-fee only, or covers
//     its participants.
//
//  3. THE DATE DISCIPLINE. Almost every national competition here reaches a
//     student through a LOCAL round whose date is set by a chapter, a school, a
//     state coordinator or a regional host. That round is the one they can
//     actually enter, and its date is genuinely not knowable from here — so
//     those entries are `confidence: 'varies'` with a prose `season`, and the
//     roadmap tells the student to find their local date and enter it rather
//     than printing one we made up. Entries carrying a `window` are the ones
//     whose registration is run centrally by the national organization.
//
// ── Why the spread is this wide ──────────────────────────────────────────────
// A student heading for biomedical engineering, one heading for public health,
// and one heading for a humanities major are all going to the same medical
// school, and the competition that is worth their year is different in each
// case (see src/lib/geo/majors.js). Writing, ethics, statistics, policy, speech
// and robotics entries are in here for exactly that reason — they are not
// padding, they are the entries that make the major question mean something.
// ─────────────────────────────────────────────────────────────────────────────

